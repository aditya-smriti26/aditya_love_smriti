const state = {
  currentPage: 0,
  isAnimating: false,
  musicPlaying: false
};

const cover = document.getElementById("cover");
const bookScreen = document.getElementById("bookScreen");
const openBookBtn = document.getElementById("openBookBtn");
const homeBtn = document.getElementById("homeBtn");
const prevBtn = document.getElementById("prevBtn");
const nextBtn = document.getElementById("nextBtn");
const pageCard = document.getElementById("pageCard");
const chapterLabel = document.getElementById("chapterLabel");
const pageTitle = document.getElementById("pageTitle");
const pageText = document.getElementById("pageText");
const pageQuote = document.getElementById("pageQuote");
const pagePhoto = document.getElementById("pagePhoto");
const photoCaption = document.getElementById("photoCaption");
const pageNumber = document.getElementById("pageNumber");
const progressBar = document.getElementById("progressBar");
const progressText = document.getElementById("progressText");
const contentsBtn = document.getElementById("contentsBtn");
const contentsPanel = document.getElementById("contentsPanel");
const contentsList = document.getElementById("contentsList");
const proposalModal = document.getElementById("proposalModal");
const yesBtn = document.getElementById("yesBtn");
const replayBtn = document.getElementById("replayBtn");
const musicBtn = document.getElementById("musicBtn");
const bgMusic = document.getElementById("bgMusic");

function openBook() {
  cover.classList.remove("active");
  bookScreen.classList.add("active");
  state.currentPage = 0;
  renderPage();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function returnToCover() {
  bookScreen.classList.remove("active");
  cover.classList.add("active");
  closeContents();
  closeProposal();
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function renderPage() {
  const page = pages[state.currentPage];

  chapterLabel.textContent = page.chapter;
  pageTitle.textContent = page.title;
  pageText.innerHTML = page.text.map(paragraph => `<p>${paragraph}</p>`).join("");
  pageQuote.textContent = `“${page.quote}”`;

  // Replace assets/photos/photo-01.svg etc. with your own JPG/PNG photos.
  const photoNumber = String(state.currentPage + 1).padStart(2, "0");
  pagePhoto.src = `assets/photos/photo-${photoNumber}.jpg`;
  pagePhoto.alt = `Photo placeholder for ${page.title}`;
  photoCaption.textContent = page.caption;

  pageNumber.textContent = `Page ${state.currentPage + 1} of ${pages.length}`;
  progressText.textContent = `${state.currentPage + 1} / ${pages.length}`;
  progressBar.style.width = `${((state.currentPage + 1) / pages.length) * 100}%`;

  prevBtn.disabled = state.currentPage === 0;
  nextBtn.innerHTML = state.currentPage === pages.length - 1
    ? "<span>Finish</span><span aria-hidden=\"true\">♥</span>"
    : "<span>Next</span><span aria-hidden=\"true\">→</span>";

  updateContentsHighlight();
}

function changePage(direction) {
  if (state.isAnimating) return;

  if (direction === 1 && state.currentPage === pages.length - 1) {
    openProposal();
    return;
  }

  const nextIndex = state.currentPage + direction;
  if (nextIndex < 0 || nextIndex >= pages.length) return;

  state.isAnimating = true;
  const animationClass = direction > 0 ? "turn-next" : "turn-prev";
  pageCard.classList.add(animationClass);

  setTimeout(() => {
    state.currentPage = nextIndex;
    renderPage();
  }, 310);

  setTimeout(() => {
    pageCard.classList.remove(animationClass);
    state.isAnimating = false;
    window.scrollTo({ top: 0, behavior: "smooth" });
  }, 630);
}

function buildContents() {
  contentsList.innerHTML = pages.map((page, index) => `
    <button class="contents-item" type="button" data-page="${index}">
      <span class="contents-number">${String(index + 1).padStart(2, "0")}</span>
      <span>${page.title}</span>
    </button>
  `).join("");

  contentsList.addEventListener("click", event => {
    const item = event.target.closest("[data-page]");
    if (!item) return;

    state.currentPage = Number(item.dataset.page);
    renderPage();
    closeContents();
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
}

function updateContentsHighlight() {
  document.querySelectorAll(".contents-item").forEach((item, index) => {
    item.classList.toggle("current", index === state.currentPage);
  });
}

function openContents() {
  contentsPanel.classList.add("open");
  contentsPanel.setAttribute("aria-hidden", "false");
}

function closeContents() {
  contentsPanel.classList.remove("open");
  contentsPanel.setAttribute("aria-hidden", "true");
}

function openProposal() {
  proposalModal.classList.add("open");
  proposalModal.setAttribute("aria-hidden", "false");
}

function closeProposal() {
  proposalModal.classList.remove("open");
  proposalModal.setAttribute("aria-hidden", "true");
}

function celebrateYes() {
  for (let index = 0; index < 55; index += 1) {
    setTimeout(() => {
      const heart = document.createElement("span");
      heart.className = "celebration-heart";
      heart.textContent = Math.random() > 0.25 ? "♥" : "✦";
      heart.style.left = `${Math.random() * 100}vw`;
      heart.style.fontSize = `${18 + Math.random() * 40}px`;
      heart.style.animationDuration = `${2.7 + Math.random() * 2}s`;
      document.body.appendChild(heart);
      setTimeout(() => heart.remove(), 5000);
    }, index * 55);
  }

  yesBtn.textContent = "Our forever begins now ♥";
  yesBtn.disabled = true;
}

function toggleMusic() {
  const hasAudioSource = bgMusic.querySelector("source") || bgMusic.getAttribute("src");

  if (!hasAudioSource) {
    musicBtn.textContent = "♪";
    musicBtn.title = "Add a music file in index.html first";
    alert("To add music, place an MP3 file in assets/music and add its path inside the <audio> element in index.html.");
    return;
  }

  if (bgMusic.paused) {
    bgMusic.play().then(() => {
      state.musicPlaying = true;
      musicBtn.textContent = "❚❚";
    }).catch(() => {
      alert("Your browser blocked autoplay. Press the music button again.");
    });
  } else {
    bgMusic.pause();
    state.musicPlaying = false;
    musicBtn.textContent = "♫";
  }
}

function createAmbientHearts() {
  const field = document.getElementById("heartField");

  for (let index = 0; index < 30; index += 1) {
    const heart = document.createElement("span");
    heart.className = "floating-heart";
    heart.textContent = "♥";
    heart.style.left = `${Math.random() * 100}%`;
    heart.style.fontSize = `${12 + Math.random() * 42}px`;
    heart.style.animationDuration = `${9 + Math.random() * 13}s`;
    heart.style.animationDelay = `${Math.random() * -20}s`;
    heart.style.setProperty("--drift", `${-70 + Math.random() * 140}px`);
    field.appendChild(heart);
  }

  for (let index = 0; index < 60; index += 1) {
    const sparkle = document.createElement("span");
    sparkle.className = "sparkle";
    sparkle.style.left = `${Math.random() * 100}%`;
    sparkle.style.top = `${Math.random() * 100}%`;
    sparkle.style.animationDelay = `${Math.random() * 3}s`;
    sparkle.style.animationDuration = `${2 + Math.random() * 3}s`;
    field.appendChild(sparkle);
  }
}

openBookBtn.addEventListener("click", openBook);
homeBtn.addEventListener("click", returnToCover);
prevBtn.addEventListener("click", () => changePage(-1));
nextBtn.addEventListener("click", () => changePage(1));
contentsBtn.addEventListener("click", openContents);
musicBtn.addEventListener("click", toggleMusic);
yesBtn.addEventListener("click", celebrateYes);

replayBtn.addEventListener("click", () => {
  closeProposal();
  state.currentPage = 0;
  renderPage();
});

document.querySelectorAll("[data-close-contents]").forEach(element => {
  element.addEventListener("click", closeContents);
});

document.addEventListener("keydown", event => {
  if (event.key === "Escape") {
    closeContents();
    closeProposal();
  }

  if (!bookScreen.classList.contains("active")) return;
  if (contentsPanel.classList.contains("open") || proposalModal.classList.contains("open")) return;

  if (event.key === "ArrowRight") changePage(1);
  if (event.key === "ArrowLeft") changePage(-1);
});

buildContents();
createAmbientHearts();
renderPage();
